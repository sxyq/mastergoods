    ADD CONSTRAINT fk_account_transfers_owner_from FOREIGN KEY (owner_user_id, from_account_id)
        REFERENCES accounts(owner_user_id, id);

ALTER TABLE account_transfers
    ADD CONSTRAINT fk_account_transfers_owner_to FOREIGN KEY (owner_user_id, to_account_id)
        REFERENCES accounts(owner_user_id, id);

ALTER TABLE cash_change_records
    ADD CONSTRAINT fk_cash_change_records_owner_account FOREIGN KEY (owner_user_id, account_id)
        REFERENCES accounts(owner_user_id, id);

