CREATE TABLE IF NOT EXISTS accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT NOT NULL,
    code VARCHAR(64) NOT NULL,
    name VARCHAR(128) NOT NULL,
    type INTEGER NOT NULL DEFAULT 1,
    balance DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    status INTEGER NOT NULL DEFAULT 1,
    sort_order INTEGER NOT NULL DEFAULT 0,
    notes VARCHAR(255),
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS account_transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT NOT NULL,
    transfer_no VARCHAR(64) NOT NULL,
    from_account_id BIGINT NOT NULL,
    to_account_id BIGINT NOT NULL,
    amount DOUBLE PRECISION NOT NULL,
    fee DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    status INTEGER NOT NULL DEFAULT 1,
    notes VARCHAR(255),
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS bill_fund_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT NOT NULL,
    bill_type VARCHAR(32) NOT NULL,
    bill_id BIGINT NOT NULL,
    account_id BIGINT NOT NULL,
    amount DOUBLE PRECISION NOT NULL,
    link_type INTEGER NOT NULL DEFAULT 1,
    notes VARCHAR(255),
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS cash_change_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT NOT NULL,
    order_type VARCHAR(32) NOT NULL,
    order_id BIGINT NOT NULL,
    receivable DOUBLE PRECISION NOT NULL,
    received DOUBLE PRECISION NOT NULL,
    change_amount DOUBLE PRECISION NOT NULL,
    account_id BIGINT,
    status INTEGER NOT NULL DEFAULT 1,
    notes VARCHAR(255),
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS inventory_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    product_code VARCHAR(64) NOT NULL,
    product_name VARCHAR(128) NOT NULL,
    warehouse_id BIGINT,
    quantity_before DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    quantity_change DOUBLE PRECISION NOT NULL,
    quantity_after DOUBLE PRECISION NOT NULL,
    unit_cost DOUBLE PRECISION,
    source_type VARCHAR(32) NOT NULL,
    source_id BIGINT,
    source_no VARCHAR(64),
    notes VARCHAR(255),
    created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS inventory_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    product_code VARCHAR(64) NOT NULL,
    product_name VARCHAR(128) NOT NULL,
    warehouse_id BIGINT,
    quantity DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    unit_cost DOUBLE PRECISION,
    total_value DOUBLE PRECISION,
    snapshot_date BIGINT NOT NULL,
    created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS inventory_monthly_stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    product_code VARCHAR(64) NOT NULL,
    product_name VARCHAR(128) NOT NULL,
    warehouse_id BIGINT,
    month INTEGER NOT NULL,
    year INTEGER NOT NULL,
    quantity_in DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    quantity_out DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    quantity_adjust DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    quantity_begin DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    quantity_end DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    total_cost_in DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    total_cost_out DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

